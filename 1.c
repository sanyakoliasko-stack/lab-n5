#include <stdio.h>  // Бібліотека для введення-виведення (printf, scanf)
#include <math.h>   // Бібліотека для математичних функцій (pow)

int main() {
    int choice;     // Змінна для зберігання вибору користувача в меню
    int n;          // Змінна для розміру масиву

    // Цикл do-while дозволяє меню працювати, поки користувач не натисне 0
    do {
        // Виводимо пункти меню в консоль
        printf("\n========= МЕНЮ УПРАВЛІННЯ =========\n");
        printf("1. Ввести масив та порахувати\n");
        printf("2. Довідка про алгоритм\n");
        printf("0. Вихід з програми\n");
        printf("Ваш вибір: ");
        
        scanf("%d", &choice); // Зчитуємо вибір користувача

        switch (choice) {
            case 1: { // Якщо вибрано "1"
                printf("Введіть кількість елементів: ");
                scanf("%d", &n);

                // Перевірка: розмір масиву не може бути нульовим або меншим
                if (n <= 0) {
                    printf("Помилка! Кількість елементів має бути > 0.\n");
                    break; // Повертаємось у головне меню
                }

                int a[n];           // Оголошуємо масив розміром n
                double product = 1.0; // Змінна для множення (старт з 1.0)
                int count = 0;      // Лічильник тільки додатніх елементів

                printf("Введіть %d елементів:\n", n);
                for (int i = 0; i < n; i++) {
                    printf("Елемент [%d]: ", i);
                    scanf("%d", &a[i]); // Зчитуємо i-й елемент масиву

                    // ПЕРЕВІРКА НА ВІД'ЄМНЕ ЧИСЛО ТА НУЛЬ
                    if (a[i] > 0) {
                        product *= a[i]; // Множимо, якщо число додатнє
                        count++;         // Рахуємо кількість додатніх
                    } else {
                        // Пояснюємо користувачу, чому це число пропущено
                        printf("  -> Число %d пропущено (воно від'ємне або 0).\n", a[i]);
                    }
                }

                // Перевірка: чи знайшли ми хоча б одне число > 0
                if (count > 0) {
                    // Середнє геометричне = добуток у ступені 1/кількість
                    double res = pow(product, 1.0 / count);
                    printf("\n--- РЕЗУЛЬТАТ ---\n");
                    printf("Знайдено додатніх елементів: %d\n", count);
                    printf("Середнє геометричне: %.4f\n", res);
                } else {
                    printf("\nПомилка: не введено жодного додатнього числа!\n");
                }
                break;
            }
            case 2: // Якщо вибрано "2"
                printf("\n--- ДОВІДКА ---\n");
                printf("Середнє геометричне рахується тільки для чисел > 0.\n");
                printf("Використовується формула: корінь n-го ступеня з добутку.\n");
                break;
            
            case 0: // Якщо вибрано "0"
                printf("Програма завершена.\n");
                break;

            default: // Якщо введено цифру, якої немає в меню
                printf("Неправильний пункт меню! Спробуйте ще раз.\n");
        }
    } while (choice != 0); // Цикл крутиться, поки choice не стане рівним 0

    return 0; // Кінець програми
}